import React from 'react';
import { useWellStore } from '../stores/wellStore';
import { useEffect, useState } from 'react';
import { getModelMetrics } from '../services/api';
import { Brain, TrendingUp, Target, Activity, Cpu } from 'lucide-react';
import OriginMlPanel from '../components/OriginMlPanel';

export const ModelMetricsPage: React.FC = () => {
  const { selectedWell } = useWellStore();
  const [metrics, setMetrics] = useState<any | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let active = true;
    setLoading(true);
    setError(null);
    getModelMetrics()
      .then((data) => { if (active) setMetrics(data); })
      .catch((err) => { if (active) setError(err?.message || 'Unable to load model metrics'); })
      .finally(() => { if (active) setLoading(false); });
    return () => { active = false; };
  }, [selectedWell]);

  const css = metrics?.css_surrogate || {};
  const risk = metrics?.failure_risk || {};
  const r2Values = Object.values(css?.r2 || {}).filter((v): v is number => typeof v === 'number' && Number.isFinite(v));
  const meanR2 = r2Values.length ? r2Values.reduce((a, b) => a + b, 0) / r2Values.length : null;

  return (
    <div className="flex flex-col gap-6 p-6">
      <div className="flex items-center gap-4 border-b border-slate-700/50 pb-6">
        <div className="p-3 bg-pink-500/20 text-pink-400 rounded-xl ring-1 ring-pink-500/30"><Brain className="w-6 h-6" /></div>
        <div>
          <h1 className="text-2xl font-bold text-white tracking-tight">ML Model Metrics</h1>
          <p className="text-slate-400 mt-1">Live metrics reported by the backend model registry · {selectedWell}</p>
        </div>
      </div>

      {error && <div className="rounded-xl border border-rose-500/30 bg-rose-500/10 p-4 text-sm text-rose-300">{error}</div>}
      {loading && <div className="rounded-xl border border-slate-700/50 bg-slate-900/50 p-4 text-sm text-slate-400">Synchronizing with backend model metrics…</div>}

      <div className="grid grid-cols-1 md:grid-cols-4 gap-4">
        <div className="bg-slate-800/40 border border-slate-700/50 rounded-xl p-5">
          <div className="flex items-center justify-between mb-4"><div className="p-2 bg-indigo-500/10 text-indigo-400 rounded-lg"><Target className="w-5 h-5" /></div><span className="text-xs font-medium text-slate-400 bg-slate-700/50 px-2 py-1 rounded-full">Backend</span></div>
          <div className="text-sm text-slate-400 font-medium mb-1">Mean R² · CSS surrogate</div>
          <div className="text-3xl font-bold text-white">{meanR2 === null ? '—' : meanR2.toFixed(3)}</div>
          <div className="mt-4 h-1.5 w-full bg-slate-900 rounded-full overflow-hidden"><div className="h-full bg-indigo-500 rounded-full" style={{ width: `${Math.max(0, Math.min(100, (meanR2 || 0) * 100))}%` }} /></div>
        </div>

        <div className="bg-slate-800/40 border border-slate-700/50 rounded-xl p-5">
          <div className="flex items-center justify-between mb-4"><div className="p-2 bg-emerald-500/10 text-emerald-400 rounded-lg"><Activity className="w-5 h-5" /></div><span className="text-xs font-medium text-slate-400 bg-slate-700/50 px-2 py-1 rounded-full">Failure Risk</span></div>
          <div className="text-sm text-slate-400 font-medium mb-1">Classifier accuracy</div>
          <div className="text-3xl font-bold text-white">{typeof risk.accuracy === 'number' ? `${(risk.accuracy * 100).toFixed(1)}%` : '—'}</div>
          <div className="mt-4 text-xs text-slate-500">Samples: {risk.n_samples ?? '—'}</div>
        </div>

        <div className="bg-slate-800/40 border border-slate-700/50 rounded-xl p-5">
          <div className="flex items-center justify-between mb-4"><div className="p-2 bg-amber-500/10 text-amber-400 rounded-lg"><TrendingUp className="w-5 h-5" /></div><span className="text-xs font-medium text-slate-400 bg-slate-700/50 px-2 py-1 rounded-full">Training</span></div>
          <div className="text-sm text-slate-400 font-medium mb-1">Training samples · CSS</div>
          <div className="text-3xl font-bold text-white">{css.n_samples ?? '—'}</div>
          <div className="mt-4 text-xs text-slate-500">Uses the report generated by backend/app/ml</div>
        </div>

        <div className="bg-slate-800/40 border border-slate-700/50 rounded-xl p-5">
          <div className="flex items-center justify-between mb-4"><div className="p-2 bg-blue-500/10 text-blue-400 rounded-lg"><Cpu className="w-5 h-5" /></div><span className="text-xs font-medium text-slate-400 bg-slate-700/50 px-2 py-1 rounded-full">Registry</span></div>
          <div className="text-sm text-slate-400 font-medium mb-1">Report generated</div>
          <div className="text-lg font-bold text-white mt-2">{metrics?.trained_at || '—'}</div>
          <div className="mt-4 text-xs text-slate-500">No synthetic latency claim is shown here.</div>
        </div>
      </div>

      <OriginMlPanel />

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        <div className="bg-slate-900/50 border border-slate-700/50 rounded-xl p-6 min-h-[300px]">
          <div className="flex items-center gap-3 mb-5"><Brain className="w-7 h-7 text-pink-400" /><div><h3 className="text-lg font-medium text-white">CSS surrogate outputs</h3><p className="text-xs text-slate-500">R² by reported target</p></div></div>
          <div className="space-y-3">
            {Object.entries(css?.r2 || {}).map(([target, value]) => (
              <div key={target} className="flex items-center justify-between text-sm"><span className="text-slate-400">{target}</span><span className="font-mono text-white">{typeof value === 'number' ? value.toFixed(3) : String(value)}</span></div>
            ))}
            {!Object.keys(css?.r2 || {}).length && <p className="text-sm text-slate-500">No CSS surrogate metrics are currently available.</p>}
          </div>
        </div>
        <div className="bg-slate-900/50 border border-slate-700/50 rounded-xl p-6 min-h-[300px]">
          <div className="flex items-center gap-3 mb-5"><Target className="w-7 h-7 text-amber-400" /><div><h3 className="text-lg font-medium text-white">Failure-risk report</h3><p className="text-xs text-slate-500">Backend classifier summary</p></div></div>
          <div className="space-y-3 text-sm">
            <div className="flex justify-between"><span className="text-slate-400">Accuracy</span><span className="font-mono text-white">{typeof risk.accuracy === 'number' ? `${(risk.accuracy * 100).toFixed(1)}%` : '—'}</span></div>
            <div className="flex justify-between"><span className="text-slate-400">Positive rate</span><span className="font-mono text-white">{typeof risk.positive_rate === 'number' ? `${(risk.positive_rate * 100).toFixed(1)}%` : '—'}</span></div>
            <div className="flex justify-between"><span className="text-slate-400">Samples</span><span className="font-mono text-white">{risk.n_samples ?? '—'}</span></div>
          </div>
        </div>
      </div>
    </div>
  );
};

export default ModelMetricsPage;
